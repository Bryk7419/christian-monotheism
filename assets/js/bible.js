const aliasToBook = new Map();
for (const b of books) for (const a of b.aliases) aliasToBook.set(a, b.id);

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const aliasPattern = [...aliasToBook.keys()]
  .sort((a, b) => b.length - a.length)
  .map((a) => escapeRe(a).replace(/ /g, ' ?'))
  .join('|');
// Название книги на границе слова, за ним — номер главы.
const REF_RE = new RegExp(`(?:^|[^\\p{L}\\d])(${aliasPattern})(?= ?\\d)`, 'gu');

// «Первое послание…» → «1 …». Без lookbehind: его нет в старых Safari.
const ORDINALS = [
  ['перв(?:ое|ая|ой|ого|ую|ом)', '1'],
  ['втор(?:ое|ая|ой|ого|ую|ом)', '2'],
  ['трет(?:ье|ья|ьей|ьего|ью|ьем)', '3'],
  ['четверт(?:ое|ая|ой|ого|ую|ом)', '4'],
].map(([word, n]) => [new RegExp(`(^|[^\\p{L}])${word}(?=\\s)`, 'gu'), n]);
// Слова, которые не меняют ссылку: «Евангелие от Иоанна», «Послание к Римлянам».
const FILLERS = /(?:^|\s)(?:святое|святого|евангелие|евангелия|от|послание|послания|к|ко|книга|книги|книге|апостола|пророка|св)(?=\s|$)/gu;

/** Нормализация строки для разбора ссылок. */
export function normalizeRefText(input) {
  let s = String(input).toLowerCase().replace(/ё/g, 'е');
  s = s.replace(/[‐-―−]/g, '-'); // все виды тире → «-»
  s = s.replace(/(\d)\s*-\s*(?:е|я|й|ое|ая|ой|го)(?![\p{L}])/gu, '$1'); // 1-е → 1
  for (const [re, n] of ORDINALS) s = s.replace(re, (_, pre) => pre + n);
  s = s.replace(/\./g, ' ');
  s = s.replace(/(\d)(?=\p{L})/gu, '$1 ').replace(/(\p{L})(?=\d)/gu, '$1 ');
  s = s.replace(/\s+/g, ' ');
  s = s.replace(FILLERS, ' ').replace(FILLERS, ' ');
  return s.replace(/\s+/g, ' ').trim();
}

// Ключ места: глава * 1000 + стих. Глава без стиха — весь диапазон главы.
const key = (c, v) => c * 1000 + v;

/**
 * Разбор числовой части после названия книги.
 * Поддерживает: «17», «17:3», «17:1-5», «17:5, 22, 24», «1:10-12, 20-21»,
 * «14-16» (главы), «13:1-14:3». В режиме query также «1 1» = «1:1».
 */
function parseNumbers(str, start, { query = false } = {}) {
  const segs = [];
  let i = start;
  const peek = () => str[i];
  const skipSpaces = () => { while (str[i] === ' ') i += 1; };
  const readInt = () => {
    const m = /^\d{1,3}/.exec(str.slice(i));
    if (!m) return null;
    i += m[0].length;
    return Number(m[0]);
  };
  skipSpaces();
  const chapter = readInt();
  if (chapter === null || chapter === 0) return { segs, end: start };
  let end = i;
  const save = () => { end = i; };

  const readVerseRange = (c) => {
    // уже прочитана глава c и разделитель; читаем стих (диапазон)
    skipSpaces();
    const v1 = readInt();
    if (v1 === null) return false;
    let c2 = c;
    let v2 = v1;
    const before = i;
    skipSpaces();
    if (peek() === '-') {
      i += 1;
      skipSpaces();
      const x = readInt();
      if (x === null) { i = before; } else {
        const afterX = i;
        skipSpaces();
        if (peek() === ':') {
          i += 1;
          skipSpaces();
          const y = readInt();
          if (y === null) { i = afterX; v2 = x; } else { c2 = x; v2 = y; }
        } else { i = afterX; v2 = x; }
      }
    } else { i = before; }
    segs.push([key(c, v1), key(c2, Math.max(v2, c2 === c ? v1 : 0))]);
    save();
    return true;
  };

  let current = chapter;
  const afterChapter = i;
  skipSpaces();
  if (peek() === ':') {
    i += 1;
    if (!readVerseRange(current)) { i = afterChapter; segs.push([key(current, 0), key(current, 999)]); save(); }
  } else if (query && /^\d/.test(str.slice(i)) && i > afterChapter) {
    // «Ин 1 1» — стих через пробел (только в поисковом запросе)
    if (!readVerseRange(current)) { i = afterChapter; segs.push([key(current, 0), key(current, 999)]); save(); }
  } else if (peek() === '-') {
    // диапазон глав «14-16»
    i += 1;
    skipSpaces();
    const c2 = readInt();
    if (c2 !== null && c2 >= current) {
      segs.push([key(current, 0), key(c2, 999)]);
      save();
    } else {
      i = afterChapter;
      segs.push([key(current, 0), key(current, 999)]);
      save();
    }
    return { segs, end };
  } else {
    i = afterChapter;
    segs.push([key(current, 0), key(current, 999)]);
    save();
    return { segs, end };
  }

  // Продолжения через запятую: «, 22, 24» или «, 20-21» или «, 18:3»
  for (;;) {
    const before = i;
    skipSpaces();
    if (peek() !== ',') { i = before; break; }
    i += 1;
    skipSpaces();
    const m = /^(\d{1,3})(?:\s*:\s*\d)?/.exec(str.slice(i));
    if (!m) { i = before; break; }
    if (m[0].includes(':')) {
      current = readInt();
      skipSpaces();
      i += 1; // «:»
    }
    if (!readVerseRange(current)) { i = before; break; }
  }
  return { segs, end };
}

/**
 * Найти все библейские ссылки в тексте.
 * Возвращает [{ book, segs: [[from, to], …], start, end }].
 * options.query — разрешить «Ин 1 1»; options.strict — требовать «:» или
 * точку после сокращения (для сканирования обычного текста статей).
 */
export function findRefs(text, options = {}) {
  const norm = normalizeRefText(text);
  const out = [];
  REF_RE.lastIndex = 0;
  let m;
  while ((m = REF_RE.exec(norm))) {
    const alias = m[1].replace(/ /g, '');
    const bookId = aliasToBook.get(m[1]) ?? [...aliasToBook.entries()].find(([a]) => a.replace(/ /g, '') === alias)?.[1];
    if (!bookId) continue;
    const startNums = m.index + m[0].length;
    const { segs, end } = parseNumbers(norm, startNums, options);
    if (!segs.length) continue;
    if (options.strict) {
      const numText = norm.slice(startNums, end);
      if (!numText.includes(':')) continue;
    }
    out.push({ book: bookId, segs, start: m.index + m[0].length - m[1].length, end });
    REF_RE.lastIndex = end;
  }
  return out;
}

/** Первая ссылка в строке (для поля passages). */
export function parsePassage(text) {
  return findRefs(text)[0] ?? null;
}

/** Пересекаются ли два набора отрезков одной книги. */
export function segsOverlap(a, b) {
  for (const [a1, a2] of a) for (const [b1, b2] of b) if (a1 <= b2 && b1 <= a2) return true;
  return false;
}

/** Ключ сортировки места в порядке книг Библии. */
export function sortKey(ref) {
  const b = getBook(ref.book);
  const first = ref.segs[0]?.[0] ?? 0;
  return (b ? b.order : 999) * 1e6 + first;
}

/** Убрать из запроса найденные ссылки, вернуть остаток текста. */
export function stripRefs(text, refs) {
  const norm = normalizeRefText(text);
  if (!refs.length) return text;
  let rest = '';
  let pos = 0;
  for (const r of refs) {
    rest += norm.slice(pos, r.start) + ' ';
    pos = r.end;
  }
  return (rest + norm.slice(pos)).trim();
}
