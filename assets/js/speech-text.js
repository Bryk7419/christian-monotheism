function declineName(name, c) {
  if (c === 4) {
    if (NAME_ACC[name]) return NAME_ACC[name];
    const k = name.match(/^(?:(\d)-я книга|Книга) (.+)$/);
    return k ? `${k[1] ? `${k[1]}-ю ` : ''}книгу ${k[2]}` : name;
  }
  if (NAME_FORMS[name]) return NAME_FORMS[name][c];
  let m = name.match(/^(\d)-я книга (.+)$/);
  if (m) return `${m[1]}${ORDINAL[c]} ${['книги', 'книге', 'книге', 'книгой'][c]} ${m[2]}`;
  m = name.match(/^Книга (.+)$/);
  if (m) return `${['книги', 'книге', 'книге', 'книгой'][c]} ${m[1]}`;
  m = name.match(/^Евангелие (.+)$/);
  if (m) return `${['Евангелия', 'Евангелии', 'Евангелию', 'Евангелием'][c]} ${m[1]}`;
  m = name.match(/^(\d)-е послание (.+)$/);
  if (m) return `${m[1]}${ORDINAL_NEUTER[c]} ${['послания', 'послании', 'посланию', 'посланием'][c]} ${m[2]}`;
  m = name.match(/^Послание (.+)$/);
  if (m) return `${['Послания', 'Послании', 'Посланию', 'Посланием'][c]} ${m[1]}`;
  return name;
}

const ABBR_BOOK = Object.fromEntries(books.map((b) => [b.abbr, b.id]));
const CHAPTER_REF = new RegExp(`(${books.map((b) => b.abbr.replace(/[.]/g, '\\.')).sort((a, b) => b.length - a.length).join('|')})`
  + '\\s?(\\d{1,3})(?:[–-](\\d{1,3}))?(?![\\d–-]|:\\d)', 'g');

function spokenRef(ref, c = null, inherited = false) {
  const b = BOOK[ref.book];
  if (ref.chapters) {
    const [c1, c2] = ref.chapters;
    const psa = ref.book === 'psa';
    let head = c1 === c2 ? `${psa ? 'псалом' : 'глава'} ${c1}` : `${psa ? 'псалмы' : 'главы'} с ${c1} по ${c2}`;
    if (psa && c !== null && c !== 4 && c1 === c2) head = `${HEAD_FORMS.псалом[c]} ${c1}`;
    return psa ? head : `${c === null ? b.name : declineName(b.name, c)}, ${head}`;
  }
  // отрезки по главам: «8:24, 28» → глава 8, стихи 24 и 28
  const groups = [];
  for (const [c1, v1, c2, v2] of ref.segs) {
    const text = c1 !== c2 ? `с ${v1} стиха главы ${c1} по ${v2} стих главы ${c2}` : (v1 === v2 ? `${v1}` : `с ${v1} по ${v2}`);
    const last = groups[groups.length - 1];
    if (last && last.c === c1 && c1 === c2) last.items.push(text);
    else groups.push({ c: c1, items: [text], range: c1 !== c2 || v1 !== v2 });
  }
  const named = ref.explicit && b && ref.book !== 'psa';
  const parts = groups.map((g, i) => {
    const many = g.items.length > 1 || g.range;
    let head = ref.book === 'psa' ? 'псалом' : 'глава';
    // падеж берёт название книги, а если его нет — первое «глава» или «псалом»
    if (c !== null && c !== 4 && i === 0 && !named && !inherited) head = HEAD_FORMS[head][c];
    return `${head} ${g.c}, ${many ? 'стихи' : 'стих'} ${g.items.join(' и ')}`;
  });
  const name = named ? `${c === null ? b.name : declineName(b.name, c)}, ` : '';
  return `${name}${parts.join('; ')}`;
}

const ROMAN = { I: 1, V: 5, X: 10, L: 50, C: 100 };
function roman(s) {
  let n = 0;
  for (let i = 0; i < s.length; i += 1) {
    const v = ROMAN[s[i]];
    n += v < (ROMAN[s[i + 1]] ?? 0) ? -v : v;
  }
  return n;
}

export function speakable(text, home) {
  let t = text.replace(/\s*\((?:внешний сайт|YouTube), откроется в новой вкладке\)/g, '')
    // «46:15–47:04 — …» в списке глав видео: отметки времени не читаются
    .replace(/^\s*\d{1,2}(?::\d{2}){1,2}\s?[–-]\s?\d{1,2}(?::\d{2}){1,2}\s*[—–-]\s*/, '').replace(/[↗\u0301]/g, '').replace(/ /g, ' ');
  // 1. ссылки → метки
  const refs = scanRefs(t, home);
  // ссылки на целую главу («Откр. 5», «Притч. 8») сканер стихов не берёт: добавляем их сами
  for (const m of t.matchAll(CHAPTER_REF)) {
    if (refs.some((r) => m.index < r.end && m.index + m[0].length > r.start)) continue;
    refs.push({ book: ABBR_BOOK[m[1]], chapters: [Number(m[2]), Number(m[3] || m[2])], explicit: true,
      start: m.index, end: m.index + m[0].length });
  }
  refs.sort((a, b) => a.start - b.start);
  for (const r of [...refs].reverse()) {
    t = `${t.slice(0, r.start)}\u0001${refs.indexOf(r)}\u0002${t.slice(r.end)}`;
  }
  // 2. скобки, где только ссылки, убираются; в остальных ссылки выбрасываются
  t = t.replace(/\s?\(([^()]*)\)/g, (all, inner) => {
    if (!inner.includes('\u0001')) return all;
    const rest = inner.replace(/\u0001\d+\u0002/g, '').replace(/(^|[;,]\s*)(ср\.|см\.)\s*/g, '$1').replace(/^[\s;,.]+|[\s;,.]+$/g, '');
    return rest ? ` (${rest})` : '';
  });
  // ссылки без книги, которые сканер не узнал («(6:2, 16)» без «Разбираемых мест»), тоже пропускаются
  t = t.replace(/\s?\(\s*\d{1,3}:\d{1,3}(?:[–-]\d{1,3})?(?:[,;]\s*\d{1,3}(?::\d{1,3})?(?:[–-]\d{1,3})?)*\s*\)/g, '');
  // 3. ссылки внутри фразы → словами, после предлога — в нужном падеже («в Ин. 8:58» → «в Евангелии от Иоанна…»);
  // через «и», «или», запятую падеж переходит на следующую ссылку («в Ин. 1:1 и Ин. 1:14»)
  let prev = null;
  t = t.replace(/([^\s\u0001\u0002]+)?(\s*)\u0001(\d+)\u0002/g, (all, word, space, i, at) => {
    const before = (word || '').toLowerCase();
    let c = space ? PREP_CASE[before] ?? (GENITIVE_AFTER.has(before) ? 0 : ACC_AFTER.has(before) ? 4 : null) : null;
    let inherited = false;
    if (c === null && prev && prev.end === at && /^(?:и|или|,)$/.test(before)) { c = prev.c; inherited = true; }
    const r = refs[Number(i)];
    let out = r ? spokenRef(r, c, inherited) : '';
    let w = word || '';
    if (before === 'об' && /^[ЕЁЮЯ]/.test(out)) w = word[0] === 'О' ? 'О' : 'о';
    prev = { c, end: at + all.length + (t.slice(at + all.length).match(/^\s*/)[0].length) };
    return `${w}${space}${out}`;
  });
  // 4. сокращения и римские цифры (до латиницы: римские цифры — тоже латинские буквы)
  t = t.replace(/(^|[\s(«])([Сс])р\.(?=\s)/g, '$1$2равните').replace(/(^|[\s(«])([Сс])м\.(?=\s)/g, '$1$2мотрите')
    .replace(/Р\.\s?Х\./g, 'Рождества Христова').replace(/\bт\.\s?е\./g, 'то есть').replace(/и т\.\s?д\./g, 'и так далее')
    .replace(/\b([IVXLC]+)(?=(?:[-–][IVXLC0-9]+)?\s+век)/g, (r) => String(roman(r)))
    .replace(/[-–]([IVXLC]+)(?=\s+век)/g, (_, r) => `-${roman(r)}`);
  // 5. греческие, еврейские и латинские вставки пропускаются: голос читает ровный русский текст.
  // Запятая сразу после вставки уходит вместе с ней: «стоит אֵלַי, «на Меня»» → «стоит «на Меня»»
  t = t.replace(/§+\s*\d*[a-z–-]*/g, '').replace(/\[\d+\]/g, '')
    .replace(GREEK_RUN, '').replace(HEBREW_RUN, (_, w, comma) => (hebrewWord(w) ? hebrewWord(w) + (comma || '') : ''))
    .replace(/\s*\([A-Z][A-Za-z]{1,6}\)/g, '')   // сокращение в скобках после полного названия: «(REV)»
    .replace(LATIN_WORD, (w) => LATIN_WORDS[w]).replace(/(\d)([abc])(?![A-Za-z])/g, (_, d, l) => `${d}-${PART_LETTER[l]}`)
    .replace(LATIN_RUN, '');
  return tidy(t);
}

